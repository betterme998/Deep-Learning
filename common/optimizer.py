"""
名optimizer表示“进行最优化的人”的意思，这里
由SGD承担这个角色。参数的更新由optimizer负责完成。我们在这里需要
做的只是将参数和梯度的信息传给optimizer。
"""
import numpy as np

class SGD:
  """
  随机梯度下降优化器（Stochastic Gradient Descent）。
  用数学式可以将SGD写成如下的式  
  W <- W - η(偏L/偏W)  
  更新的权重参数记为W  
  损失函数关于W的梯度记为(偏L/偏W)  
  η表示学习率，实际上会取0.01或0.001这些事先决定好的值

  SGD是朝着梯度方向只前进一定距离的简单方法

  1.SGD的缺点  
  梯度的方向并没有指向最小值的方向。  
  如果函数的形状非均向（anisotropic），比如呈延伸状，搜索的路径就会非常低效。

  这种更新有两个典型问题：  
  锯齿震荡：当损失函数的“地形”是狭长山谷（病态曲率）时，梯度方向会频繁拐弯，导致参数在垂直于谷底的方向上来回震荡，前进缓慢。

  停滞在平坦区/鞍点：梯度过小甚至为零时，参数几乎不再更新，训练被困住。
  """
  # 最简单的参数更新方式：param = param - learning_rate * gradient
  def __init__(self, lr=0.01):
    """
    初始化优化器。
    
    参数：
        lr: float, 学习率（learning rate），控制参数更新的步长。
    """
    self.lr = lr

  def update(self, params, grads):
    """
    根据梯度更新参数。
    
    参数：
        params: dict, 模型参数字典，键为参数名，值为参数值（如numpy数组）。
        grads:  dict, 梯度字典，键与params相同，值为对应参数的梯度。
    """
    for key in params.keys():
      # 核心更新公式：参数 -= 学习率 × 梯度
      params[key] -= self.lr * grads[key]

class Momentum:
  """
  物理直觉：滚下山的小球  
  给梯度下降加上“惯性”

  普通 SGD：小球每次只受当前“推力”（梯度）移动，完全没有惯性，一遇到小坑就停，稍有不平就剧烈抖动。

  带动量的 SGD：小球像有了质量和惯性，它会记住之前的运动方向。当梯度方向一致时，小球加速；当梯度方向来回变时，惯性会平滑震荡；遇到平坦区域，它还能靠惯性冲过去，甚至越过一些小的局部极小点。  

  Momentum是“动量”的意思，和物理有关。用数学式表示Momentum方法，如下所示  
  v <- αv - η(偏L/偏W) # 物体在梯度方向上受力，在这个力的作用下，物体的速度增加这一物理法则。  
  W <- W + v

  W:表示要更新的权重参数  
  (偏L/偏W):表示损失函数关于W的梯度  
  η:表示学习率  
  v:速度（动量项），累积了历史梯度。  
  αv:表示速度的衰减率，α的值通常取0.9或0.99。(对应物理上的地面摩擦或空气阻力)  

  为什么这样能起作用？  
  1.方向一致的梯度被增强：连续指向同一方向的梯度会不断累加，步伐越来越大，实现加速。  
  2.方向震荡的梯度相互抵消：例如在峡谷中，垂直于谷底的方向梯度来回翻转，加权平均后接近零，震荡被抑制；沿谷底方向梯度持续积累，有效位移增大。  
  3.逃离鞍点与平坦区：即使当前梯度很小，历史累积的速度 v不为零，依然能继续前进，有机会脱离鞍点。
  """
  def __init__(self, lr=0.01, momentum=0.9):
    """
    初始化动量优化器。

    参数:
        lr: 学习率 (learning rate)，控制每次更新的步长。
        momentum: 动量系数，通常取 0~1 之间的值，决定历史梯度的影响程度。
    """
    self.lr = lr
    self.momentum = momentum
    self.v = None # 速度（动量项），将在第一次更新时初始化为与参数形状相同的零数组

  def updata(self, params, grads):
    """
    使用动量方法更新参数（方法名应为 update，此处保留原拼写）。

    参数:
        params: 字典，键为参数名，值为对应的参数数组（将被原地更新）。
        grads:  字典，键为参数名，值为对应的梯度数组。
    """
    if self.v is None: # 第一次调用时，初始化速度 v 为与参数形状相同的全零字典
      self.v = {}
      for key, val in params.items():
        self.v[key] = np.zeros_like(val) # 创建形状一致的全零数组

    # 对每一个参数进行动量更新
    for key in params.keys():
      # 动量更新公式：v = momentum * v - lr * grad
      self.v[key] = self.momentum*self.v[key] - self.lr*grads[key]
      # 参数更新：param = param + v
      params[key] += self.v[key]

class AdaGrad:
  """
  在神经网络的学习中，学习率（数学式中记为η）的值很重要。学习率过小，  
  会导致学习花费过多时间；反过来，学习率过大，则会导致学习发散而不能  
  正确进行。

  在关于学习率的有效技巧中，有一种被称为学习率衰减（learning rate  
  decay）的方法，即随着学习的进行，使学习率逐渐减小。

  逐渐减小学习率的想法，相当于将“全体”参数的学习率值一起降低。  
  而AdaGrad[6]进一步发展了这个想法，针对“一个一个”的参数，赋予其“定  
  制”的值

  AdaGrad会为参数的每个元素适当地调整学习率，与此同时进行学习  
  （AdaGrad的Ada来自英文单词Adaptive，即“适当的”的意思）。

  设计初衷：为每个参数量身定做学习率。

  1. 它要解决什么问题？  
    标准的梯度下降（SGD）对所有参数使用同一个全局学习率。这会带来两个麻烦：  
    .稀疏特征难学习：比如在 NLP 中，“the”出现几万次，而“斑马”只出现几次。同一个学习率下，高频特征可能已经过拟合或震荡，低频特征的参数却还没怎么更新。

  .手动调参痛苦：为了平衡不同参数的更新步伐，往往需要精细地衰减学习率，非常依赖经验。

  2. 核心公式与直观理解  
    AdaGrad的核心公式是：  
    h <- h + (偏L/偏W)^2    
    W <- W - η / (√h + ε) \* (偏L/偏W)  
    
    W:表示要更新的权重参数  
    (偏L/偏W):表示损失函数关于W的梯度  
    η表示学习率
    ε:防止除零
    h:表示历史梯度平方和，用来计算学习率。

  3. 优点与致命缺陷

  优点：  
  .特别适合稀疏数据，对低频特征极其友好。  
  .减少了手动调节学习率的痛苦，算法会自适应地衰减。  
  .理论上能更鲁棒地处理不同尺度的梯度（因为每个参数根据自身历史缩放）。

  缺点（正是这个缺点催生了 RMSProp 和 Adam）：  
  .学习率单调递减，最后趋近于零。 因为 h 是累加所有历史的平方梯度，永远不会减小。训练到中后期，所有参数的学习率都会变得极小，模型几乎停止学习，即使此时还没收敛到理想状态。

  .对于密集特征或深层网络，梯度一直存在，学习率衰减过快，往往早早陷入停滞。

  4. AdaGrad 怎么理解？  
  它为每个参数配备了一个“计数器”，记录了该参数历史上看到过的梯度有多“猛”。更新越频繁、梯度越大的参数，学习率降得越快；更新越稀少的参数，学习率几乎不降，保持大步更新。这种机制天然适合稀疏特征，但因为计数器只增不减，最终所有参数的学习率都会趋零，导致训练提前终止。
  """